import type Phaser from "phaser";
import type { Theme } from "./stage";

/** Trace real landmarks in the shipped 1536×1024 paintings, retaining their brushwork. */
export function makeBackgroundObjects(scene: Phaser.Scene, theme: Theme) {
  const source = scene.textures.get("world").getSourceImage() as HTMLImageElement;
  const cut = (key: string, points: number[][]) => {
    if (scene.textures.exists(key)) return;
    const left = Math.min(...points.map(p => p[0])) - 2, top = Math.min(...points.map(p => p[1])) - 2;
    const width = Math.max(...points.map(p => p[0])) - left + 2, height = Math.max(...points.map(p => p[1])) - top + 2;
    const texture = scene.textures.createCanvas(key, width, height);
    if (!texture) return;
    const ctx = texture.context;
    ctx.translate(-left, -top);
    ctx.beginPath(); points.forEach(([x,y], i) => i ? ctx.lineTo(x,y) : ctx.moveTo(x,y)); ctx.closePath();
    ctx.clip(); ctx.drawImage(source, 0, 0, 1536, 1024); texture.refresh();
  };
  if (theme === "ice") {
    cut("iceberg", [[278,469],[294,444],[298,388],[308,412],[316,340],[327,365],[334,307],[346,293],[359,311],[366,375],[376,356],[390,416],[402,427],[411,455],[419,469],[400,480],[365,479],[337,476],[312,483],[287,479]]);
    cut("icicle", [[1035,282],[1056,279],[1052,300],[1047,343],[1043,355],[1039,322]]);
  }
  const shores: Record<Theme, number[][]> = {
    sea: [[504,508],[529,492],[545,470],[564,475],[574,435],[586,431],[594,413],[608,430],[621,423],[632,440],[643,404],[654,393],[665,418],[680,415],[694,438],[708,425],[724,446],[753,438],[769,447],[779,444],[798,457],[816,460],[842,486],[832,514],[807,529],[792,554],[775,535],[745,523],[727,521],[710,551],[694,520],[666,515],[637,543],[619,511],[586,534],[562,517],[535,517]],
    ice: [[778,405],[798,390],[827,375],[852,372],[876,354],[897,342],[915,339],[936,311],[948,304],[966,325],[975,337],[998,334],[1006,357],[1020,362],[1030,397],[1010,416],[980,421],[950,418],[918,421],[875,413],[841,424],[809,418]],
    desert: [[969,458],[984,449],[998,432],[1010,432],[1015,411],[1031,405],[1043,412],[1054,406],[1073,419],[1094,419],[1114,426],[1128,450],[1146,444],[1167,454],[1194,458],[1206,469],[1181,476],[1137,477],[1102,471],[1071,479],[1033,470],[1000,475]],
    cloud: [[921,296],[936,286],[947,273],[960,272],[970,223],[978,205],[988,227],[991,263],[1001,250],[1015,255],[1024,220],[1036,208],[1043,222],[1048,253],[1063,244],[1074,221],[1083,209],[1094,233],[1102,249],[1120,247],[1136,268],[1152,272],[1170,290],[1160,312],[1135,318],[1106,337],[1096,313],[1061,324],[1045,317],[1024,339],[1005,312],[975,323],[955,310],[932,311]],
  };
  cut(`harbor-shore-${theme}`, shores[theme]);
}
